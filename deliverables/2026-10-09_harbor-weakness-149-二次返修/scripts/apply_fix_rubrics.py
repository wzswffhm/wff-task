def crlf(s):
    return s.replace('\n', '\r\n')


def apply(path, pairs, label):
    data = path.read_bytes()
    txt = data.decode('utf-8')
    for old, new in pairs:
        o, n = crlf(old), crlf(new)
        cnt = txt.count(o)
        if cnt != 1:
            print(f'  [FAIL] {label}: 命中 {cnt} 次（期望 1）：{old[:60]!r}')
            return False
        txt = txt.replace(o, n)
    path.write_bytes(txt.encode('utf-8'))
    return True


